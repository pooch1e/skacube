/**
 * Tests for the data hooks and the GraphQL wrapper against stubbed fetch
 * responses: success, GraphQL errors, HTTP errors, and volume bytes.
 */
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { renderHook, waitFor } from "@testing-library/react";
import type { ReactNode } from "react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { useDataset, useVolume } from "./hooks";

function wrapper() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  return function Wrapper({ children }: { children: ReactNode }) {
    return <QueryClientProvider client={client}>{children}</QueryClientProvider>;
  };
}

function stubFetch(response: Response) {
  const fetchMock = vi.fn<typeof fetch>(async () => response);
  vi.stubGlobal("fetch", fetchMock);
  return fetchMock;
}

const dataset = {
  id: "synthetic",
  title: "Synthetic test cube",
  unit: "K",
  sourceUrl: "https://example.invalid/synthetic",
  citation: "Generated by data/test_ingest.py",
  volumeSha256: "abc",
  shape: { ra: 16, dec: 16, frequency: 16 },
  axes: [],
  stretch: { limitK: 0.1, softeningK: 0.005, zeroByte: 128 },
  header: [{ key: "BUNIT", value: "K" }],
};

afterEach(() => {
  vi.unstubAllGlobals();
});

describe("useDataset", () => {
  it("posts the typed query and returns the dataset", async () => {
    const fetchMock = stubFetch(Response.json({ data: { dataset } }));

    const { result } = renderHook(() => useDataset("synthetic"), { wrapper: wrapper() });

    await waitFor(() => expect(result.current.isSuccess).toBe(true));
    expect(result.current.data).toEqual(dataset);
    const [url, init] = fetchMock.mock.calls[0] as [string, RequestInit];
    expect(url).toBe("/graphql");
    expect(JSON.parse(init.body as string)).toMatchObject({ variables: { id: "synthetic" } });
  });

  it("returns null for an unknown id", async () => {
    stubFetch(Response.json({ data: { dataset: null } }));

    const { result } = renderHook(() => useDataset("nope"), { wrapper: wrapper() });

    await waitFor(() => expect(result.current.isSuccess).toBe(true));
    expect(result.current.data).toBeNull();
  });

  it("is an error when the response has GraphQL errors", async () => {
    stubFetch(Response.json({ data: null, errors: [{ message: "boom" }] }));

    const { result } = renderHook(() => useDataset("synthetic"), { wrapper: wrapper() });

    await waitFor(() => expect(result.current.isError).toBe(true));
    expect(result.current.error?.message).toBe("boom");
  });

  it("is an error on a non-2xx response", async () => {
    stubFetch(new Response("down", { status: 502 }));

    const { result } = renderHook(() => useDataset("synthetic"), { wrapper: wrapper() });

    await waitFor(() => expect(result.current.isError).toBe(true));
    expect(result.current.error?.message).toContain("502");
  });
});

describe("useVolume", () => {
  it("returns the bytes as a Uint8Array", async () => {
    const bytes = new Uint8Array([0, 128, 255, 7]);
    const fetchMock = stubFetch(new Response(bytes));

    const { result } = renderHook(() => useVolume("synthetic"), { wrapper: wrapper() });

    await waitFor(() => expect(result.current.isSuccess).toBe(true));
    expect(result.current.data).toBeInstanceOf(Uint8Array);
    expect(Array.from(result.current.data ?? [])).toEqual([0, 128, 255, 7]);
    expect(fetchMock.mock.calls[0]?.[0]).toBe("/data/volume/synthetic");
  });

  it("is an error for an unknown id", async () => {
    stubFetch(new Response(null, { status: 404 }));

    const { result } = renderHook(() => useVolume("nope"), { wrapper: wrapper() });

    await waitFor(() => expect(result.current.isError).toBe(true));
    expect(result.current.error?.message).toContain("404");
  });
});
